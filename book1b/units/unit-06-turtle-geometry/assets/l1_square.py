# Bring in Python's turtle drawing tools.
import turtle

# Draw a blue square one side at a time.
turtle.pencolor("blue")
turtle.pensize(3)

turtle.forward(82)
turtle.left(90)
turtle.forward(82)
turtle.left(90)
turtle.forward(82)
turtle.left(90)
turtle.forward(82)
turtle.left(90)

# Keep the window open until you close it.
turtle.done()
