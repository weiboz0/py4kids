"""Generated tracks as waypoints, plus the track-relative queries the runner needs (design 013 §4.3).

Tracks are produced by ``roar/data/generate.py`` into ``roar/data/generated/tracks/<name>.npz``
(gitignored, regenerated by CI). ``load_track`` reads one by name or by path.
"""

from __future__ import annotations

import math
import os
from pathlib import Path
from typing import Dict, List, Optional, Tuple, Union

import numpy as np

from .roar_py_interface import RoarPyWaypoint

FIELDS = ("x", "y", "z", "yaw", "half_width", "s", "curvature")
TRACK_NAMES = ("oval", "test-circuit", "monza-like")
GRIP_SECTIONS = 6  # the public grip-section rule (plan roar-004): equal arc-length sixths of a lap
# roar/projects/racekit/racekit/tracks.py -> roar/data/generated/tracks
_DEFAULT_DIR = Path(__file__).resolve().parents[3] / "data" / "generated" / "tracks"


def tracks_dir() -> Path:
    """Where generated tracks live (``RACEKIT_TRACKS_DIR`` overrides the in-repo default)."""
    override = os.environ.get("RACEKIT_TRACKS_DIR")
    return Path(override) if override else _DEFAULT_DIR


class Track:
    """A closed track: centreline waypoints at about 2 m spacing with a drivable half-width."""

    def __init__(
        self,
        name: str,
        x: np.ndarray,
        y: np.ndarray,
        yaw: np.ndarray,
        half_width: np.ndarray,
        z: Optional[np.ndarray] = None,
        s: Optional[np.ndarray] = None,
        curvature: Optional[np.ndarray] = None,
    ) -> None:
        self.name = name
        self.x = np.asarray(x, dtype=np.float64)
        self.y = np.asarray(y, dtype=np.float64)
        n = self.x.size
        self.z = np.zeros(n) if z is None else np.asarray(z, dtype=np.float64)
        self.yaw = np.asarray(yaw, dtype=np.float64)
        self.half_width = np.broadcast_to(np.asarray(half_width, dtype=np.float64), (n,)).copy()
        seg = np.hypot(np.diff(np.r_[self.x, self.x[:1]]), np.diff(np.r_[self.y, self.y[:1]]))
        self.length = float(seg.sum())
        self.s = np.concatenate(([0.0], np.cumsum(seg)[:-1])) if s is None else np.asarray(s, float)
        self.curvature = np.zeros(n) if curvature is None else np.asarray(curvature, float)
        # plain-float copies for the per-tick queries (much faster than numpy scalars)
        self._xs: List[float] = self.x.tolist()
        self._ys: List[float] = self.y.tolist()
        self._hw: List[float] = self.half_width.tolist()

    def __len__(self) -> int:
        return self.x.size

    def __repr__(self) -> str:
        return f"Track({self.name!r}, {self.length:.1f} m, {len(self)} waypoints)"

    @property
    def waypoints(self) -> List[RoarPyWaypoint]:
        """One lap of waypoints, as a submission receives them (``lane_width`` = 2 × half-width)."""
        return [
            RoarPyWaypoint((self.x[i], self.y[i], self.z[i]), (0.0, 0.0, self.yaw[i]), 2.0 * self.half_width[i])
            for i in range(len(self))
        ]

    def start_pose(self) -> Tuple[float, float, float]:
        """The race start: on waypoint 0, facing along the track."""
        return float(self.x[0]), float(self.y[0]), float(self.yaw[0])

    def nearest(self, px: float, py: float, hint: int, reach: int = 8) -> Tuple[int, float, float, float]:
        """Track-relative position near waypoint ``hint``.

        Searches the segments ``hint - reach .. hint + reach`` (cyclic) and returns
        ``(segment index, signed offset from the centreline (left positive), s along the lap,
        interpolated half-width)``.
        """
        xs, ys, n = self._xs, self._ys, len(self._xs)
        best = (math.inf, hint, 0.0, 0.0)
        for k in range(hint - reach, hint + reach + 1):
            i = k % n
            j = (i + 1) % n
            ax, ay = xs[i], ys[i]
            dx, dy = xs[j] - ax, ys[j] - ay
            seg2 = dx * dx + dy * dy
            t = ((px - ax) * dx + (py - ay) * dy) / seg2
            t = max(0.0, min(t, 1.0))
            ex, ey = px - (ax + t * dx), py - (ay + t * dy)
            d2 = ex * ex + ey * ey
            if d2 < best[0]:
                best = (d2, i, t, (dx * ey - dy * ex) / math.sqrt(seg2))
        _, i, t, offset = best
        j = (i + 1) % n
        s = float(self.s[i]) + t * math.hypot(xs[j] - xs[i], ys[j] - ys[i])
        width = self._hw[i] + t * (self._hw[j] - self._hw[i])
        return i, offset, s, width

    def locate(self, px: float, py: float) -> Tuple[int, float, float]:
        """A global (whole-lap) track-relative query: ``(segment index, offset, s)``. For analysis."""
        d2 = (self.x - px) ** 2 + (self.y - py) ** 2
        i, offset, s, _ = self.nearest(px, py, int(np.argmin(d2)), reach=2)
        return i, offset, s

    def arrays(self) -> Dict[str, np.ndarray]:
        return {field: getattr(self, field) for field in FIELDS}


def grip_sections(track: Track) -> np.ndarray:
    """The grip section of every waypoint: the lap cut into ``GRIP_SECTIONS`` equal arc-length
    sections from the start waypoint (waypoint 0 opens section 0).

    The rule is public (any generated track, seeded checkpoint tracks included); the μ of each
    section is not.
    """
    return np.minimum((track.s / track.length * GRIP_SECTIONS).astype(int), GRIP_SECTIONS - 1)


def load_track(name_or_path: Union[str, Path, Track]) -> Track:
    """Load a generated track by name (``"oval"``, ``"test-circuit"``, ``"monza-like"``) or path."""
    if isinstance(name_or_path, Track):
        return name_or_path
    path = Path(name_or_path)
    if path.suffix != ".npz":
        path = tracks_dir() / f"{name_or_path}.npz"
    if not path.is_file():
        raise FileNotFoundError(
            f"no generated track at {path}; run "
            "`PYTHONHASHSEED=0 uv run --group roar python roar/data/generate.py` from the repo root"
        )
    with np.load(path) as data:
        arrays = {field: data[field] for field in FIELDS}
    return Track(
        path.stem, arrays["x"], arrays["y"], arrays["yaw"], arrays["half_width"],
        z=arrays["z"], s=arrays["s"], curvature=arrays["curvature"],
    )
